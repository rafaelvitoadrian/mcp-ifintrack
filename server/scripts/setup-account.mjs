#!/usr/bin/env node
/**
 * Interactive CLI helper to configure or switch Financial Tracker MCP account.
 * Supports:
 *   1) Email / Username + Password
 *   2) Direct Bearer Token
 * Writes credentials ONLY to local server/.env (gitignored) and never prints passwords/tokens.
 */
import readline from "node:readline/promises";
import { stdin as input, stdout as output } from "node:process";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const envPath = path.resolve(__dirname, "..", ".env");

async function loadExistingEnv() {
  try {
    const raw = await fs.readFile(envPath, "utf-8");
    const map = new Map();
    for (const line of raw.split(/\r?\n/)) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith("#")) continue;
      const eq = trimmed.indexOf("=");
      if (eq > 0) {
        map.set(trimmed.slice(0, eq).trim(), trimmed.slice(eq + 1).trim());
      }
    }
    return map;
  } catch {
    return new Map();
  }
}

async function main() {
  const rl = readline.createInterface({ input, output });
  try {
    const existing = await loadExistingEnv();
    const defaultApiUrl =
      existing.get("FINTRACK_API_BASE_URL") ||
      "https://dev-ifintrack.rafaelvito.online";
    const defaultTz = existing.get("FINTRACK_TIMEZONE") || "Asia/Jakarta";

    console.log("\n=== Pengaturan / Ganti Akun MCP Financial Tracker ===");
    const apiUrlInput = (
      await rl.question(`Base URL Backend [${defaultApiUrl}]: `)
    ).trim();
    const apiBaseUrl = (apiUrlInput || defaultApiUrl).replace(/\/+$/, "");

    console.log("\nPilih metode autentikasi:");
    console.log("  1) Email / Username + Password");
    console.log("  2) Bearer Token langsung");
    const mode = (await rl.question("Pilihan [1/2] (default 1): ")).trim() || "1";

    let email = "";
    let password = "";
    let token = "";

    if (mode === "2") {
      token = (await rl.question("Masukkan Bearer Token: ")).trim();
      if (!token) {
        throw new Error("Token tidak boleh kosong.");
      }
    } else {
      email = (await rl.question("Masukkan Email / Username: ")).trim();
      password = await rl.question("Masukkan Password: ");
      if (!email || !password) {
        throw new Error("Email/Username dan Password wajib diisi.");
      }
    }

    const scheduleUrlInput = (
      await rl.question(
        `URL Daily Schedule opsional [${existing.get("FINTRACK_SCHEDULE_BASE_URL") || "kosong"}]: `,
      )
    ).trim();
    const scheduleBaseUrl =
      scheduleUrlInput || existing.get("FINTRACK_SCHEDULE_BASE_URL") || "";

    const lines = [
      "# Generated by setup-account.mjs (DO NOT COMMIT)",
      `FINTRACK_API_BASE_URL=${apiBaseUrl}`,
      `FINTRACK_SCHEDULE_BASE_URL=${scheduleBaseUrl}`,
      `FINTRACK_TIMEZONE=${defaultTz}`,
      `PORT=${existing.get("PORT") || "3000"}`,
      `APPROVAL_TIMEOUT_MS=${existing.get("APPROVAL_TIMEOUT_MS") || "900000"}`,
      `REQUEST_TIMEOUT_MS=${existing.get("REQUEST_TIMEOUT_MS") || "30000"}`,
      `WRITE_TIMEOUT_MS=${existing.get("WRITE_TIMEOUT_MS") || "240000"}`,
      `MAX_RESULT_SIZE=${existing.get("MAX_RESULT_SIZE") || "48000"}`,
      `FINTRACK_UPLOAD_DIR=${existing.get("FINTRACK_UPLOAD_DIR") || ""}`,
      `FINTRACK_EMAIL=${email}`,
      `FINTRACK_PASSWORD=${password}`,
      `FINTRACK_TOKEN=${token}`,
      "",
    ];

    await fs.writeFile(envPath, lines.join("\n"), { encoding: "utf-8", mode: 0o600 });
    console.log(`\nKonfigurasi akun tersimpan ke ${envPath}`);
    console.log(
      mode === "2"
        ? "Metode aktif: Bearer Token langsung."
        : `Metode aktif: Email/Username (${email}) + Password.`,
    );
    console.log(
      "Silakan restart MCP server / client Anda agar sesi baru langsung aktif.",
    );
  } finally {
    rl.close();
  }
}

main().catch((err) => {
  console.error("Gagal mengatur akun:", err instanceof Error ? err.message : err);
  process.exit(1);
});
